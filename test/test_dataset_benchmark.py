#!/usr/bin/env python3
import json
import tempfile
import unittest
from pathlib import Path

import numpy as np
import yaml
from scipy.spatial.transform import Rotation

import benchmark_common as common


class DatasetBenchmarkTest(unittest.TestCase):
    def trajectory(self, transform=None):
        time = np.arange(0.0, 5.01, 0.05)
        position = np.column_stack([time, np.sin(time), 0.2*time])
        quaternion = Rotation.from_euler("z", 0.1*time).as_quat()
        if transform is not None:
            rotation, translation = transform
            position = (rotation @ position.T).T + translation
            quaternion = (Rotation.from_matrix(rotation) *
                          Rotation.from_quat(quaternion)).as_quat()
        return common.Trajectory(time, position, quaternion)

    def test_known_truth_metrics(self):
        metrics, _ = common.evaluate_trajectories(self.trajectory(), self.trajectory())
        self.assertLess(metrics["ape_translation_m_rmse"], 1e-12)
        self.assertLess(metrics["rpe_1s_translation_m_rmse"], 1e-12)
        self.assertLess(metrics["ape_rotation_deg_rmse"], 1e-10)

    def test_alignment_is_diagnostic_without_scale(self):
        rotation = Rotation.from_euler("z", 0.7).as_matrix()
        estimate = self.trajectory((rotation, np.array([2.0, -1.0, 0.5])))
        metrics, _ = common.evaluate_trajectories(estimate, self.trajectory())
        self.assertGreater(metrics["ape_translation_m_rmse"], 1.0)
        self.assertLess(metrics["ape_se3_aligned_translation_m_rmse"], 1e-10)

    def test_tag_lever_projection(self):
        position = np.array([1.0, 2.0, 3.0])
        quat = Rotation.from_euler("z", 90, degrees=True).as_quat()
        actual = common.apply_tag_lever(position, quat, [1.0, 0.0, 0.0])
        np.testing.assert_allclose(actual, [1.0, 3.0, 3.0], atol=1e-12)

    def test_six_configs_describe_forty_runs(self):
        configs = [yaml.safe_load(path.read_text()) for path in
                   sorted((common.ROOT/"config/benchmark").glob("*.yaml"))]
        self.assertEqual(len(configs), 6)
        count = 0
        for config in configs:
            if config["sequences"] == "all":
                count += len(json.loads((common.ROOT/config["data_root"]/
                    config["sequence_manifest"]).resolve().read_text()))
            else:
                count += len(config["sequences"])
        self.assertEqual(count, 40)

    def test_own_calibration_is_rigid_and_disclosed(self):
        path = common.ROOT/"results/benchmark/calibration/own_vicon_joint.json"
        if not path.is_file():
            self.skipTest("calibration artifact is generated by prepare")
        calibration = json.loads(path.read_text())
        matrix = np.asarray(calibration["rotation_body_from_imu_matrix"])
        np.testing.assert_allclose(matrix.T@matrix, np.eye(3), atol=1e-8)
        self.assertAlmostEqual(np.linalg.det(matrix), 1.0, places=8)
        self.assertEqual(calibration["gt_use"],
                         "interface_rotation_time_and_translation_only")

    def test_unit_and_offset_contracts(self):
        configs = {yaml.safe_load(path.read_text())["dataset"]:
                   yaml.safe_load(path.read_text()) for path in
                   (common.ROOT/"config/benchmark").glob("*.yaml")}
        self.assertEqual(configs["HUEC"]["imu"]["acceleration_unit"], "mps2")
        self.assertEqual(configs["HUEC"]["imu"]["gyro_unit"], "radps")
        self.assertEqual(configs["own_vicon"]["imu"]["acceleration_scale"], 9.80665)
        self.assertEqual(configs["starloc"]["imu"]["rotation"],
                         "C_r_i=C_c_r^T*C_c_i")
        cache = common.ROOT/"results/benchmark/cache/SFUISE/ISAS-Walk1"
        if cache.is_dir():
            manifest = json.loads((cache/"manifest.json").read_text())
            offsets = manifest["provenance"]["toa_offset_by_anchor"]
            rows = common.read_csv(cache/"uwb.csv")
            for row in rows[:100]:
                expected = float(offsets.get(str(int(row["anchor_id"])),
                                             offsets.get(int(row["anchor_id"]))))
                self.assertAlmostEqual(float(row["range"])-float(row["range_raw"]),
                                       expected, places=9)

    def test_interpolation_rejects_large_brackets(self):
        trajectory = common.Trajectory(
            np.array([0.0, 1.0]), np.zeros((2, 3)),
            np.tile(np.array([0.0, 0.0, 0.0, 1.0]), (2, 1)))
        valid, _, _ = common.interpolate(trajectory, np.array([0.5]), max_bracket_s=.2)
        self.assertFalse(valid[0])
        valid, position, _ = common.interpolate(
            trajectory, np.array([0.0, 1.0]), max_bracket_s=.2)
        self.assertTrue(valid.all())
        self.assertEqual(position.shape, (2, 3))

    def test_cache_gt_is_evaluator_only(self):
        manifests = list((common.ROOT/"results/benchmark/cache").glob("*/*/manifest.json"))
        if not manifests:
            self.skipTest("caches are generated by prepare")
        for path in manifests:
            manifest = json.loads(path.read_text())
            self.assertNotIn("gt.csv", manifest["estimator_inputs"])
            self.assertIn("gt.csv", manifest["evaluator_only"])
            hashes = manifest["provenance"].get("source_file_sha256", {})
            self.assertTrue(hashes)
            self.assertTrue(all(len(value) == 64 for value in hashes.values()))
        runner = (common.ROOT/"apps/nominal_dataset_runner.cpp").read_text()
        self.assertNotIn('"gt.csv"', runner)
        for forbidden in ("IntegrityMonitor", "RealtimeIntegrityPipeline",
                          "ProtectionLevel", "Bridge"):
            self.assertNotIn(forbidden, runner)
        realtime = (common.ROOT/"tools/run_realtime_integrity.cpp").read_text()
        self.assertIn("subscribe_truth_topics", realtime)


if __name__ == "__main__":
    unittest.main()
